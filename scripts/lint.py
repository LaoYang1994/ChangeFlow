#!/usr/bin/env python3
"""Lint ChangeFlow's own contracts (see docs/CONTRACTS.md). Stdlib only.

Usage:
    python3 scripts/lint.py [--root <plugin-root>]

Exit 0 = every check passed; 1 = at least one failed. Run before committing,
together with `claude plugin validate . --strict`.
"""
import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if "--root" in sys.argv:
    ROOT = Path(sys.argv[sys.argv.index("--root") + 1]).resolve()
GEN_MARK = "<!-- GENERATED by ChangeFlow scripts/sync-codex.py"

failures = []


def check(ok, msg):
    print(("  ok    " if ok else "  FAIL  ") + msg)
    if not ok:
        failures.append(msg)


def section(title):
    print(f"\n[{title}]")


def run(cmd, **kw):
    return subprocess.run(cmd, capture_output=True, text=True, **kw)


def frontmatter(text):
    lines = text.replace("\r\n", "\n").split("\n")
    if not lines or lines[0].strip() != "---":
        return {}, text
    end = next((i for i in range(1, len(lines)) if lines[i].strip() == "---"), None)
    if end is None:
        return {}, text
    meta = {}
    for ln in lines[1:end]:
        if ":" in ln:
            k, v = ln.split(":", 1)
            meta[k.strip()] = v.strip()
    return meta, "\n".join(lines[end + 1:])


cmds = sorted(ROOT.glob("commands/*.md"))
names = {c.stem for c in cmds}

# ------------------------------------------------------------------ commands
section("commands/*.md")
check(len(cmds) > 0, f"found {len(cmds)} commands")
for c in cmds:
    meta, body = frontmatter(c.read_text())
    d = meta.get("description", "")
    check(d.startswith("Use when"), f"{c.stem}: description starts with 'Use when'")
    check(len(d) <= 250, f"{c.stem}: description <= 250 chars ({len(d)})")
    check(" — " not in d, f"{c.stem}: description has no ' — ' step-summary clause (trigger-only)")
    if c.stem.startswith("change-"):
        check("human-initiated" in d.lower(), f"{c.stem}: description says Human-initiated")
    check(("argument-hint" in meta) == ("$ARGUMENTS" in body),
          f"{c.stem}: argument-hint and $ARGUMENTS agree")
    check("Open with:" in body, f"{c.stem}: has an 'Open with:' line")

# ------------------------------------------------- Status markers / T# tasks
section("lifecycle markers")
design = (ROOT / "commands/change-design.md").read_text()
plan = (ROOT / "commands/change-plan.md").read_text()
check("\nStatus: draft" in design, "design.md template has a Status line")
plan_tpl = plan.split("## plan.md template", 1)[-1]
check("\nStatus: draft" in plan_tpl, "plan.md template has a Status line")
bad = [l for l in plan_tpl.splitlines() if l.startswith("- [ ]") and not re.match(r"- \[ \] T\d+ ", l)]
check(not bad, f"plan.md template: every checkbox is a T# task (offenders: {bad})")
impl = (ROOT / "commands/change-implement.md").read_text()
check("Status: frozen" in impl, "change-implement gates on Status: frozen")

# ------------------------------------------------- change docs & worktrees
section("change docs live with the code")
locs = {}
for n in ("change-plan", "change-plan-review", "change-implement", "change-review",
          "change-validate", "change-archive"):
    m = re.search(r"A change's docs live in its worktree[^\n]*", (ROOT / f"commands/{n}.md").read_text())
    locs[n] = m.group(0) if m else None
check(all(locs.values()), f"locate-the-change sentence present (missing in: {[k for k, v in locs.items() if not v]})")
check(len({v for v in locs.values() if v}) <= 1, "locate-the-change sentence is identical in every command")
check("every worktree" in design, "change-design looks for changes across worktrees")
check("move the change's docs into it" in impl, "change-implement moves the docs into the worktree")
stale_hits = []
for f in (list(ROOT.glob("commands/*.md")) + list(ROOT.glob("templates/*.md"))
          + list(ROOT.glob("docs/*.md")) + [ROOT / "README.md", ROOT / "AGENTS.md"]):
    if re.search(r"stay in the main tree|always stay in the main tree", f.read_text()):
        stale_hits.append(f.name)
check(not stale_hits, f"no leftover 'docs stay in the main tree' wording (in: {stale_hits})")
archive = (ROOT / "commands/change-archive.md").read_text()
check("only once the branch is merged" in archive, "change-archive removes a worktree only after merge")

# -------------------------------------------------------------- README table
section("README / cross-references")
readme = (ROOT / "README.md").read_text()
table = set(re.findall(r"^\| `/([a-z-]+)` \|", readme, re.M))
check(table == names,
      f"README command table matches commands/ (missing: {sorted(names - table)}, extra: {sorted(table - names)})")
ref = re.compile(r"(?<![\w/.~-])/((?:change|changeflow|experience|workflow|docs)-[a-z]+(?:-[a-z]+)*)(?![\w*-])")
files = (list(ROOT.glob("commands/*.md")) + list(ROOT.glob("templates/*.md"))
         + [ROOT / "README.md", ROOT / "AGENTS.md", ROOT / "CLAUDE.md"]
         + list(ROOT.glob("docs/*.md")) + list(ROOT.glob("docs/workflows/*.md")))
unknown = {}
for f in files:
    if f.is_file():
        for m in ref.findall(f.read_text()):
            if m not in names:
                unknown.setdefault(f.name, set()).add(m)
check(not unknown, f"every /command mentioned in docs exists (unknown: {unknown})")

# ----------------------------------------------------------------- manifests
section("manifests / files")
try:
    pj = json.loads((ROOT / ".claude-plugin/plugin.json").read_text())
    mj = json.loads((ROOT / ".claude-plugin/marketplace.json").read_text())
    check(True, "plugin.json and marketplace.json are valid JSON")
    mv = [p.get("version") for p in mj.get("plugins", []) if p.get("name") == pj.get("name")]
    check(mv == [pj.get("version")], f"version agrees (plugin.json={pj.get('version')}, marketplace={mv})")
except Exception as e:  # noqa: BLE001
    check(False, f"manifests readable: {e}")
check((ROOT / "LICENSE").is_file(), "LICENSE file exists")
check(not (ROOT / "CLAUDE.md").exists(), "no CLAUDE.md at the plugin root (claude plugin validate --strict warns)")
for f in ("AGENTS.md", "templates/AGENTS.md"):
    check("Don't put scratch files in `/tmp`" in (ROOT / f).read_text(), f"{f}: has the no-/tmp scratch rule")
check("tmp/" in (ROOT / ".gitignore").read_text().splitlines(), ".gitignore ignores tmp/")
init_txt = (ROOT / "scripts/init.sh").read_text()
missing = [t for t in re.findall(r'\$PLUGIN_ROOT/(templates/[A-Za-z_.]+)', init_txt) if not (ROOT / t).is_file()]
check(not missing, f"every template init.sh copies exists (missing: {missing})")
check(".agents/skills" in init_txt and "CODEX_HOME" not in init_txt, "init.sh targets the documented Codex paths (.agents/skills)")

# ---------------------------------------------------------- sync-codex smoke
section("sync-codex.py smoke test")
sync = str(ROOT / "scripts/sync-codex.py")
with tempfile.TemporaryDirectory() as tmp:
    out = Path(tmp) / "skills"
    r = run([sys.executable, sync, str(ROOT / "commands"), str(out)])
    check(r.returncode == 0, "runs (exit 0)")
    gen = sorted(p.name for p in out.iterdir()) if out.is_dir() else []
    check(gen == sorted(names - {"changeflow-init"}), "generates every command except changeflow-init")
    problems = []
    for n in gen:
        skill = (out / n / "SKILL.md").read_text()
        if "$ARGUMENTS" in skill or GEN_MARK not in skill:
            problems.append(f"{n}: leftover $ARGUMENTS or missing GENERATED header")
        y = out / n / "agents" / "openai.yaml"
        if n.startswith("change-") != (y.is_file() and "allow_implicit_invocation: false" in y.read_text()):
            problems.append(f"{n}: agents/openai.yaml wrong (change-* only)")
        for ref_name in ref.findall(skill):
            if ref_name in gen:
                problems.append(f"{n}: still mentions /{ref_name} (Codex mentions skills with ${ref_name})")
    check(not problems, f"generated skills are well-formed {problems}")
    stale = out / "change-gone"
    stale.mkdir()
    (stale / "SKILL.md").write_text(GEN_MARK + " -->\n")
    mine = out / "my-own-skill"
    mine.mkdir()
    (mine / "SKILL.md").write_text("# not ours\n")
    r = run([sys.executable, sync, str(ROOT / "commands"), str(out)])
    check("stale" in r.stdout and stale.exists(), "reports stale generated skill without deleting it")
    run([sys.executable, sync, str(ROOT / "commands"), str(out), "--prune"])
    check(not stale.exists() and mine.exists(), "--prune removes only stale generated skills")

# ---------------------------------------------------------------- init smoke
section("init.sh smoke test")
init = str(ROOT / "scripts/init.sh")
for tools in ("claude", "codex", "both"):
    with tempfile.TemporaryDirectory() as tmp:
        tgt = Path(tmp) / "repo"
        tgt.mkdir()
        env = dict(os.environ, CODEX_SKILLS_DIR=str(Path(tmp) / "codex-skills"))
        cmd = ["bash", init, str(ROOT), str(tgt), "--tools", tools]
        r1 = run(cmd, env=env)
        (tgt / "AGENTS.md").write_text("EDITED\n")
        r2 = run(cmd, env=env)
        check(r1.returncode == 0 and r2.returncode == 0, f"--tools {tools}: exits 0 (first and repeat run)")
        check((tgt / "AGENTS.md").read_text() == "EDITED\n", f"--tools {tools}: never overwrites existing files")
        check((tgt / "CLAUDE.md").exists() == (tools != "codex"), f"--tools {tools}: CLAUDE.md only for claude")
        check((Path(tmp) / "codex-skills/change-plan/SKILL.md").exists() == (tools != "claude"),
              f"--tools {tools}: Codex skills installed only for codex")
        check(not (tgt / ".agents").exists(), f"--tools {tools}: no .agents/ in the repo unless --codex-in-repo")

with tempfile.TemporaryDirectory() as tmp:
    tgt = Path(tmp) / "repo"
    tgt.mkdir()
    env = dict(os.environ, CODEX_SKILLS_DIR=str(Path(tmp) / "should-stay-empty"))
    r = run(["bash", init, str(ROOT), str(tgt), "--tools", "codex", "--codex-in-repo"], env=env)
    check(r.returncode == 0 and (tgt / ".agents/skills/change-plan/SKILL.md").exists(),
          "--codex-in-repo vendors skills into <repo>/.agents/skills")
    check(not (Path(tmp) / "should-stay-empty").exists(), "--codex-in-repo leaves the user-level dir alone")
with tempfile.TemporaryDirectory() as tmp:
    home = Path(tmp) / "home"
    (home / ".codex/skills/change-plan").mkdir(parents=True)
    tgt = Path(tmp) / "repo"
    tgt.mkdir()
    env = {k: v for k, v in os.environ.items() if k != "CODEX_SKILLS_DIR"}
    env["HOME"] = str(home)
    r = run(["bash", init, str(ROOT), str(tgt), "--tools", "codex"], env=env)
    check((home / ".agents/skills/change-plan/SKILL.md").exists(), "default Codex install goes to ~/.agents/skills")
    check("older ChangeFlow installs" in r.stdout, "warns about legacy ~/.codex/skills copies")

print()
if failures:
    print(f"lint FAILED: {len(failures)} check(s)")
    sys.exit(1)
print("lint passed")
