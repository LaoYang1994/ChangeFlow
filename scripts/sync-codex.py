#!/usr/bin/env python3
"""Generate Codex project skills from ChangeFlow's canonical Claude commands.

Usage:
    python3 sync-codex.py <commands-dir> <output-skills-dir> [--force] [--prune]

For each command file (except changeflow-init), writes
<output-skills-dir>/<name>/SKILL.md with Codex frontmatter (name, description)
followed by the command body.

By default existing SKILL.md files are left untouched (non-destructive /
idempotent); pass --force to regenerate them after editing the commands.

Generated skills carry a GENERATED header. Skills carrying it whose command no
longer exists are reported as stale; pass --prune to delete them (skills without
the header are never touched).

Codex-specific transforms:
- change-* skills also get agents/openai.yaml with
  `policy.allow_implicit_invocation: false`, so Codex only runs them when the
  user explicitly invokes them (`$change-plan`), never on its own.
- Claude's `$ARGUMENTS` placeholder — which Codex does NOT substitute — is
  rewritten to plain wording so the generated skill reads correctly.
- Command mentions such as `/change-plan` become `$change-plan` (Codex mentions
  skills with `$`).
"""
import re
import shutil
import sys
from pathlib import Path

SKIP = {"changeflow-init"}
EXPLICIT_ONLY_PREFIX = "change-"
OPENAI_YAML = "policy:\n  allow_implicit_invocation: false\n"
GEN_MARK = "<!-- GENERATED by ChangeFlow scripts/sync-codex.py"
ARGS_PLACEHOLDER = "$ARGUMENTS"
ARGS_REPLACEMENT = "(the text the user provided when invoking this skill; may be empty)"


def parse_frontmatter(text):
    """Return (meta: dict, body: str).

    Frontmatter is recognized ONLY when the first line is exactly '---' and a
    later line is exactly '---'. Flat 'key: value' pairs only (values may
    contain colons; split once). CRLF tolerated. Anything else => no
    frontmatter, everything is body (so a body that opens with a '---'
    horizontal rule is never mistaken for frontmatter).
    """
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    lines = text.split("\n")
    if not lines or lines[0].strip() != "---":
        return {}, text
    close = next((i for i in range(1, len(lines)) if lines[i].strip() == "---"), None)
    if close is None:
        return {}, text
    meta = {}
    for line in lines[1:close]:
        if line.strip() and ":" in line:
            k, v = line.split(":", 1)
            meta[k.strip()] = v.strip()
    body = "\n".join(lines[close + 1:]).lstrip("\n")
    return meta, body


def quote(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    force = "--force" in sys.argv[1:]
    prune = "--prune" in sys.argv[1:]
    if len(args) != 2:
        print(__doc__)
        sys.exit(1)
    commands_dir, out_dir = Path(args[0]), Path(args[1])
    if not commands_dir.is_dir():
        print(f"error: commands dir not found: {commands_dir}", file=sys.stderr)
        sys.exit(1)

    wrote, skipped = [], []
    gen_names = sorted({c.stem for c in commands_dir.glob("*.md")} - SKIP, key=len, reverse=True)
    cmd_refs = re.compile(r"(?<![\w/.~-])/(" + "|".join(map(re.escape, gen_names)) + r")(?![\w*-])")
    dollar = lambda m: "$" + m.group(1)
    for cmd in sorted(commands_dir.glob("*.md")):
        name = cmd.stem
        if name in SKIP:
            continue
        out_file = out_dir / name / "SKILL.md"
        if out_file.exists() and not force:
            skipped.append(name)
            continue
        meta, body = parse_frontmatter(cmd.read_text())
        desc = meta.get("description", name).strip().strip('"')
        body = body.replace(ARGS_PLACEHOLDER, ARGS_REPLACEMENT)
        desc = cmd_refs.sub(dollar, desc)
        body = cmd_refs.sub(dollar, body)
        out_file.parent.mkdir(parents=True, exist_ok=True)
        out_file.write_text(
            "---\n"
            f"name: {name}\n"
            f"description: {quote(desc)}\n"
            "---\n\n"
            f"{GEN_MARK} from commands/{name}.md; do not edit — regenerate with --force. -->\n\n"
            f"{body.rstrip()}\n"
        )
        if name.startswith(EXPLICIT_ONLY_PREFIX):
            yaml_file = out_file.parent / "agents" / "openai.yaml"
            yaml_file.parent.mkdir(parents=True, exist_ok=True)
            yaml_file.write_text(OPENAI_YAML)
        wrote.append(name)

    print(f"codex skills -> {out_dir}  (wrote {len(wrote)}, skipped {len(skipped)})")
    for n in wrote:
        print(f"  wrote: {n}")
    for n in skipped:
        print(f"  skip (exists; use --force): {n}")

    known = {c.stem for c in commands_dir.glob("*.md")} - SKIP
    if out_dir.is_dir():
        for d in sorted(out_dir.iterdir()):
            skill = d / "SKILL.md"
            if d.name in known or not skill.is_file() or GEN_MARK not in skill.read_text():
                continue
            if prune:
                shutil.rmtree(d)
                print(f"  pruned (no longer in commands/): {d.name}")
            else:
                print(f"  stale (no longer in commands/; --prune removes it): {d.name}")


if __name__ == "__main__":
    main()
